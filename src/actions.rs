use gpui::{App, KeyBinding, actions};

use crate::editor::CONTEXT;

actions!(
    seesvee,
    [
        Open,
        MakeDefaultApp,
        NewFile,
        Quit,
        Minimize,
        Save,
        SaveAs,
        CloseWindow,
        Undo,
        Redo,
        Copy,
        Cut,
        Paste,
        SelectAll,
        ClearCells,
        MoveUp,
        MoveDown,
        MoveLeft,
        MoveRight,
        SelectUp,
        SelectDown,
        SelectLeft,
        SelectRight,
        MoveToTop,
        MoveToBottom,
        MoveToRowStart,
        MoveToRowEnd,
        SelectToTop,
        SelectToBottom,
        SelectToRowStart,
        SelectToRowEnd,
        PageUp,
        PageDown,
        MoveNext,
        MovePrev,
        StartEdit,
        Escape,
        ToggleProblems,
        ClearAllFilters,
        ClearSort,
        InsertRowAbove,
        InsertRowBelow,
        DeleteRows,
        InsertColumnLeft,
        InsertColumnRight,
        DeleteColumns,
        FilterColumn,
        ReloadComma,
        ReloadSemicolon,
        ReloadTab,
        ReloadPipe,
    ]
);

pub fn bind_keys(cx: &mut App) {
    let e = Some(CONTEXT);
    cx.bind_keys([
        KeyBinding::new("cmd-o", Open, None),
        KeyBinding::new("cmd-n", NewFile, None),
        KeyBinding::new("cmd-q", Quit, None),
        KeyBinding::new("cmd-m", Minimize, None),
        KeyBinding::new("cmd-s", Save, None),
        KeyBinding::new("cmd-shift-s", SaveAs, None),
        KeyBinding::new("cmd-w", CloseWindow, None),
        KeyBinding::new("cmd-z", Undo, e),
        KeyBinding::new("cmd-shift-z", Redo, e),
        KeyBinding::new("cmd-c", Copy, e),
        KeyBinding::new("cmd-x", Cut, e),
        KeyBinding::new("cmd-v", Paste, e),
        KeyBinding::new("cmd-a", SelectAll, e),
        KeyBinding::new("backspace", ClearCells, e),
        KeyBinding::new("delete", ClearCells, e),
        KeyBinding::new("up", MoveUp, e),
        KeyBinding::new("down", MoveDown, e),
        KeyBinding::new("left", MoveLeft, e),
        KeyBinding::new("right", MoveRight, e),
        KeyBinding::new("shift-up", SelectUp, e),
        KeyBinding::new("shift-down", SelectDown, e),
        KeyBinding::new("shift-left", SelectLeft, e),
        KeyBinding::new("shift-right", SelectRight, e),
        KeyBinding::new("cmd-up", MoveToTop, e),
        KeyBinding::new("cmd-down", MoveToBottom, e),
        KeyBinding::new("cmd-left", MoveToRowStart, e),
        KeyBinding::new("cmd-right", MoveToRowEnd, e),
        KeyBinding::new("home", MoveToRowStart, e),
        KeyBinding::new("end", MoveToRowEnd, e),
        KeyBinding::new("cmd-shift-up", SelectToTop, e),
        KeyBinding::new("cmd-shift-down", SelectToBottom, e),
        KeyBinding::new("cmd-shift-left", SelectToRowStart, e),
        KeyBinding::new("cmd-shift-right", SelectToRowEnd, e),
        KeyBinding::new("pageup", PageUp, e),
        KeyBinding::new("pagedown", PageDown, e),
        KeyBinding::new("tab", MoveNext, e),
        KeyBinding::new("shift-tab", MovePrev, e),
        KeyBinding::new("enter", StartEdit, e),
        KeyBinding::new("f2", StartEdit, e),
        KeyBinding::new("shift-enter", MoveUp, e),
        KeyBinding::new("escape", Escape, e),
        KeyBinding::new("cmd-shift-f", FilterColumn, e),
        KeyBinding::new("cmd-shift-l", ClearAllFilters, e),
        KeyBinding::new("cmd-shift-m", ToggleProblems, e),
    ]);
}
